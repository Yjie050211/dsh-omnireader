#!/usr/bin/env node
/**
 * Build script for dsh-omnireader.
 *
 * Produces two runtime artifacts:
 *   - lib/client.js          : the DSH client-half bundle, wrapped in the
 *                              window.__ModuleLoader__.load({ id, factory })
 *                              contract that DSH uses for installed plugins.
 *   - lib/pdf.worker.min.mjs : a verbatim copy of the pdf.js worker. The host
 *                              half serves it from /api/omnireader/asset so the
 *                              client can start the worker from a blob URL
 *                              without inflating the JS bundle by ~1.4 MiB.
 *
 * The host half (index.js) is plain ESM and is used as-is.
 */
import { build } from 'esbuild'
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

// ---------------------------------------------------------------------------
// 1. pdf.js worker asset
// ---------------------------------------------------------------------------
const workerCandidates = [
  join(root, 'node_modules', 'pdfjs-dist', 'build', 'pdf.worker.min.mjs'),
  join(root, 'node_modules', 'pdfjs-dist', 'legacy', 'build', 'pdf.worker.min.mjs'),
]

let worker = null
for (const candidate of workerCandidates) {
  try {
    await stat(candidate)
    worker = candidate
    break
  } catch {
    // try next candidate
  }
}

if (worker === null) {
  console.warn(
    '[omnireader] pdf.js worker not found: the PDF renderer will report a clear ' +
      'load error until `pnpm install` has populated pdfjs-dist.',
  )
} else {
  await mkdir(join(root, 'lib'), { recursive: true })
  await copyFile(worker, join(root, 'lib', 'pdf.worker.min.mjs'))
  const { size } = await stat(join(root, 'lib', 'pdf.worker.min.mjs'))
  console.log(`[omnireader] copied pdf.js worker (${(size / 1024).toFixed(1)} KiB) to lib/`)

  // The worker source is also inlined into a generated module so the client
  // can start it from a blob: URL without depending on a host route (host
  // halves only pick up new routes after a DSH restart).
  const workerSource = await readFile(worker, 'utf8')
  await mkdir(join(root, 'src', 'client', 'generated'), { recursive: true })
  await writeFile(
    join(root, 'src', 'client', 'generated', 'pdf-worker.js'),
    '/* generated by build.mjs — pdf.js worker source for offline blob: workers */\n' +
      `export const PDF_WORKER_TEXT = ${JSON.stringify(workerSource)}\n`,
    'utf8',
  )
  console.log('[omnireader] generated src/client/generated/pdf-worker.js')
}

// ---------------------------------------------------------------------------
// 2. client bundle
// ---------------------------------------------------------------------------
const result = await build({
  entryPoints: [join(root, 'src', 'client', 'entry.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome110', 'edge110'],
  jsx: 'automatic',
  logLevel: 'warning',
  charset: 'utf8',
  legalComments: 'none',
  minify: false,
  external: [
    'react',
    'react/jsx-runtime',
    'react-dom',
    'react-dom/client',
    '@deepseek-ai/cordis',
    'zod',
    '@tanstack/react-virtual',
    '@deepseek-ai/dsh-client-store',
    '@deepseek-ai/dsh-client-ui-slots',
    '@deepseek-ai/dsh-client-ui-primitives',
    '@deepseek-ai/dsh-client-ui-dockkit',
  ],
  define: {
    'process.env.NODE_ENV': '"production"',
  },
  loader: {
    '.woff': 'binary',
    '.woff2': 'binary',
    '.ttf': 'binary',
  },
})

const code = result.outputFiles[0].text
const banner = `/* dsh-omnireader client bundle — generated by build.mjs, do not edit directly */`
const wrapped = `${banner}
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkg.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${code}
\t\treturn module.exports;
\t},
});
`

await mkdir(join(root, 'lib'), { recursive: true })
await writeFile(join(root, 'lib', 'client.js'), wrapped, 'utf8')

const size = (await stat(join(root, 'lib', 'client.js'))).size
console.log(`[omnireader] built lib/client.js (${(size / 1024).toFixed(1)} KiB) from src/client/entry.jsx`)
